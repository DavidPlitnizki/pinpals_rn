// Generates public/legal.html — the public Privacy Policy / Terms page that App Store Connect
// links to — from the same text the in-app screen renders (src/shared/legalContent.ts).
//
//   npm run build:legal
//
// public/legal.html is fully overwritten: edit the TS source, not the output.
//
//   npm run build:legal -- --check
//
// verifies the committed output is up to date instead of writing it — that is what CI runs, so
// a legal edit that never got regenerated fails the build rather than shipping a stale public
// page. TypeScript is loaded via Node's type stripping (--experimental-strip-types, a no-op
// flag on Node 23.6+ where stripping is on by default).

import { readFile, writeFile } from 'node:fs/promises';
