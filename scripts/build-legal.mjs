const outPath = resolve(root, 'public/legal.html');

if (process.argv.includes('--check')) {
  const current = await readFile(outPath, 'utf8').catch(() => null);
  if (current !== html) {
    console.error(
      'public/legal.html is out of date with src/shared/legalContent.ts.\n' +
        'Run `npm run build:legal` and commit the result.',
    );
    process.exit(1);
  }
  console.log('public/legal.html is up to date.');
} else {
  await writeFile(outPath, html, 'utf8');
  console.log(`Wrote ${outPath} (${html.length} bytes), last updated ${LEGAL_LAST_UPDATED}`);
}
